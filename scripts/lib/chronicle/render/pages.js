// Chronicle's reader pages (PRD CH-09, §7): README, RELEASES and IDEAS, built
// as shared-look reports (verdict, summary, what to do, detail, glossary).
// Pure: records in, report objects out; renderReport turns them into Markdown
// and HTML. The page date is the newest record's date, never "today", so two
// renders of the same records are byte-identical.
import { readerDate } from "../../report/render.js";
import { TYPE_ORDER } from "./changelog.js";

export const BANNER = "Generated by Syno. Edit with /syno commands.";
export const FOOTER = "Made by Syno Chronicle from the records in .syno/.";
export const STATUS_ORDER = ["in-progress", "planned", "accepted", "proposed", "shipped", "parked", "rejected"];
export const STATUS_LABEL = { proposed: "Proposed", accepted: "Accepted", planned: "Planned", "in-progress": "In progress", shipped: "Shipped", parked: "Parked", rejected: "Rejected" };
export const GLOSSARY = {
  release: { term: "Release", meaning: "A numbered version of the project that was finished and handed over." },
  version: { term: "Version", meaning: "The release number, such as 1.2.0. A bigger first number means bigger changes." },
  pending: { term: "Waiting change", meaning: "Work that is finished but not yet part of a release." },
  idea: { term: "Idea", meaning: "Something someone suggested building, tracked until it ships or is set aside." },
  published: { term: "Published", meaning: "Where a release was made available, such as an app store or website." },
  folder: { term: "Folder", meaning: "A group of the project's files, such as src for its main code." },
};

export const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/** "No changes are waiting…" reads better than "0 changes are waiting…". */
export const waiting = (n) => (n ? `${plural(n, "change is", "changes are")} waiting for the next release.` : "No changes are waiting for the next release.");

/** "12.4 KB"; bytes below 1 KB stay in bytes. */
export function size(bytes) {
  const units = ["bytes", "KB", "MB", "GB"];
  let n = Math.abs(bytes);
  let u = 0;
  while (n >= 1024 && u < units.length - 1) {
    n /= 1024;
    u += 1;
  }
  const text = u ? `${n.toFixed(n < 10 ? 1 : 0)} ${units[u]}` : `${n} bytes`;
  return bytes < 0 ? `-${text}` : text;
}

/** "3 added, 2 fixed" for a list of changes. */
export function changeCounts(changes) {
  const parts = TYPE_ORDER.map((t) => [t, changes.filter((c) => c.type === t).length]).filter(([, n]) => n);
  return parts.length ? parts.map(([t, n]) => `${n} ${t.toLowerCase()}`).join(", ") : "none";
}

/** The newest date found in any record, so the page date never depends on the clock. */
export function latestDate(data) {
  const dates = [
    ...data.releases.flatMap((r) => [r.date, r.yanked?.date, ...r.channels.map((c) => c.date)]),
    ...data.ideas.map((i) => i.updated),
    ...data.pending.map((c) => c.created),
    ...data.snapshots.map((s) => s.date),
  ].filter(Boolean);
  return dates.sort().at(-1) ?? "1970-01-01";
}

export function page(data, title, extra) {
  return { title, project: data.project, date: latestDate(data), eyebrow: "Syno Chronicle", banner: BANNER, footer: FOOTER, actions: [], ...extra };
}

function latestVerdict(data) {
  const latest = data.releases[0];
  const breaking = data.pending.some((c) => c.breaking);
  if (!latest) return { level: "green", text: `No release yet. ${plural(data.pending.length, "change is", "changes are")} waiting for the first one.` };
  if (latest.status === "yanked") return { level: "amber", text: `Version ${latest.version} was withdrawn. The release before it is the one to use.` };
  if (breaking) return { level: "amber", text: `Version ${latest.version} is the latest. The next release has a change that may break things.` };
  return { level: "green", text: `Version ${latest.version} is the latest release, from ${readerDate(latest.date)}.` };
}

export function readmePage(data) {
  const latest = data.releases[0];
  const open = data.ideas.filter((i) => ["proposed", "accepted", "planned", "in-progress"].includes(i.status)).length;
  const counts = STATUS_ORDER.map((s) => [STATUS_LABEL[s], data.ideas.filter((i) => i.status === s).length]);
  return page(data, "Project record", {
    verdict: latestVerdict(data),
    howToRead: "This page is the front door to the project's record. Each row below links to a page with the full story.",
    summary: [
      latest ? `The latest release is ${latest.version}, from ${readerDate(latest.date)}.` : "There is no release yet.",
      waiting(data.pending.length),
      `${plural(data.ideas.length, "idea")} recorded, and ${open} still open.`,
      `${plural(data.releases.length, "release")} so far.`,
    ],
    sections: [
      { heading: "Pages in this record", table: { columns: [{ label: "Page" }, { label: "What it shows" }], rows: [["RELEASES.md", "Every release, what changed and where it was published"], ["IDEAS.md", "Every idea and where it stands"], ["STRUCTURE.md", "How the project's folders changed"], ["TIMELINE.md", "Everything that happened, newest first"], ["../../CHANGELOG.md", "The standard change log"]] } },
      { heading: "Ideas by status", table: { columns: [{ label: "Status" }, { label: "Ideas", num: true }], rows: counts.map(([l, n]) => [l, String(n)]) } },
    ],
    glossary: [GLOSSARY.release, GLOSSARY.version, GLOSSARY.pending, GLOSSARY.idea],
  });
}

function releaseSection(r, data) {
  const snap = data.snapshots.find((s) => s.id === r.version);
  const d = snap?.diffFromPrevious;
  const structure = !d ? null : [d.added.length && plural(d.added.length, "folder") + " added", d.removed.length && plural(d.removed.length, "folder") + " removed", d.renamed.length && plural(d.renamed.length, "folder") + " renamed"].filter(Boolean).join(", ") || "no folder changes";
  const ideas = r.ideas.map((id) => `${id} ${data.ideas.find((i) => i.id === id)?.title ?? ""}`.trim());
  return {
    heading: `${r.version} · ${readerDate(r.date)}${r.status === "yanked" ? " · Withdrawn" : ""}`,
    text: r.summary || undefined,
    list: [...TYPE_ORDER.flatMap((t) => r.changes.filter((c) => c.type === t).map((c) => `${t}: ${c.summary}${c.breaking ? " (may break things)" : ""}`)), ...ideas.map((i) => `Idea shipped: ${i}`)],
    table: r.channels.length ? { columns: [{ label: "Published to" }, { label: "Status" }, { label: "Date" }, { label: "Link" }], rows: r.channels.map((c) => [c.channel, c.status, c.date ? readerDate(c.date) : "", c.url ?? ""]) } : undefined,
    note: [r.yanked && `Withdrawn on ${readerDate(r.yanked.date)}: ${r.yanked.reason}`, structure && `Structure: ${structure}.`].filter(Boolean).join(" ") || undefined,
  };
}

export function releasesPage(data) {
  const latest = data.releases[0];
  const rows = data.releases.map((r) => [r.version, readerDate(r.date), changeCounts(r.changes), String(r.ideas.length), r.channels.filter((c) => c.status === "published").map((c) => c.channel).join(", ") || "Not recorded", r.status === "yanked" ? "Withdrawn" : "Released"]);
  return page(data, "Releases", {
    verdict: latestVerdict(data),
    howToRead: "Each row is one version, newest first. Below the table, each version lists what changed and where it was published.",
    summary: [
      `${plural(data.releases.length, "release")} so far.`,
      latest ? `The latest is ${latest.version}, with ${changeCounts(latest.changes)}.` : "The first release hasn't happened yet.",
      `${plural(data.releases.reduce((n, r) => n + r.ideas.length, 0), "idea")} shipped across all releases.`,
      waiting(data.pending.length),
    ],
    sections: [
      { heading: "Release register", table: { columns: [{ label: "Version" }, { label: "Date" }, { label: "Changes" }, { label: "Ideas shipped", num: true }, { label: "Published to" }, { label: "Status" }], rows } },
      ...data.releases.map((r) => releaseSection(r, data)),
    ],
    glossary: [GLOSSARY.release, GLOSSARY.version, GLOSSARY.published, GLOSSARY.pending],
  });
}

export function ideasPage(data) {
  const counts = STATUS_ORDER.map((s) => [s, data.ideas.filter((i) => i.status === s)]);
  const pie = counts.filter(([, l]) => l.length).map(([s, l]) => `  "${STATUS_LABEL[s]}" : ${l.length}`);
  const since = (i) => i.statusHistory.at(-1)?.date ?? i.updated;
  const groups = counts
    .filter(([, list]) => list.length)
    .map(([s, list]) => ({
      heading: STATUS_LABEL[s],
      table: { columns: [{ label: "ID" }, { label: "Idea" }, { label: "Since" }, { label: "Shipped in" }], rows: [...list].sort((a, b) => (since(b) < since(a) ? -1 : since(b) > since(a) ? 1 : a.id < b.id ? 1 : -1)).map((i) => [i.id, i.title, readerDate(since(i)), i.shippedIn ?? ""]) },
    }));
  const open = data.ideas.filter((i) => ["proposed", "accepted", "planned", "in-progress"].includes(i.status)).length;
  return page(data, "Ideas", {
    verdict: { level: "green", text: `${plural(data.ideas.length, "idea")} recorded: ${open} open and ${counts.find(([s]) => s === "shipped")[1].length} shipped.` },
    howToRead: "Ideas are grouped by where they stand, newest first. An idea is shipped only when a release includes it.",
    summary: [
      `${plural(data.ideas.length, "idea")} recorded in total.`,
      `${counts.find(([s]) => s === "in-progress")[1].length} in progress and ${counts.find(([s]) => s === "planned")[1].length} planned.`,
      `${counts.find(([s]) => s === "proposed")[1].length} new ideas are waiting for a decision.`,
      `${counts.find(([s]) => s === "parked")[1].length} parked and ${counts.find(([s]) => s === "rejected")[1].length} set aside for good.`,
    ],
    sections: [
      { heading: "Ideas by status", mermaid: pie.length ? `pie title Ideas by status\n${pie.join("\n")}` : undefined, table: { columns: [{ label: "Status" }, { label: "Ideas", num: true }], rows: counts.map(([s, l]) => [STATUS_LABEL[s], String(l.length)]) } },
      ...groups,
    ],
    glossary: [GLOSSARY.idea, GLOSSARY.release],
  });
}
