// Pages Syno Console writes for people (PRD S-17, design 5.10, 5.11): the
// decision register and the session rulebook. Each page carries a marker line,
// and Syno rewrites a page only when it is missing or still carries that
// marker, so a project's hand-written register or rulebook is never touched.
// Pure: records and config come in as data.
import { namesFor } from "./model.mjs";

export const GENERATED = "<!-- Generated by Syno Console from .syno/console/. Change the records, not this page. -->";

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const byId = (a, b) => String(a.id).localeCompare(String(b.id), "en", { numeric: true });

/** The register: one row per decision, oldest first, with replaced decisions marked. */
export function registerPage(decisions) {
  const replacedBy = {};
  for (const d of decisions) if (d.supersedes) replacedBy[d.supersedes] = d.id;
  const rows = [...decisions].sort(byId).map((d) => `| ${cell(d.decidedAt?.slice(0, 10))} | ${cell(d.scope)} | ${cell(d.question)} | ${cell(d.chosen)}${replacedBy[d.id] ? ` (replaced by ${replacedBy[d.id]})` : ""} | ${d.id} |`);
  return [
    "# Syno decision register",
    "",
    GENERATED,
    "",
    "The owner's decisions, recorded once by Syno Console. Read this before asking the owner anything. A decision is never edited: a newer one replaces it.",
    "",
    "| Date | Scope | Question | Owner's answer | ID |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

function example(id, cfg) {
  try {
    const n = namesFor(id, "", cfg);
    return { title: n.title, branch: n.branch };
  } catch {
    return { title: id, branch: "(set console.branches)" };
  }
}

const ASK = {
  console: "Only Syno Console asks the owner, always as 2 to 4 choices with the recommended one first. Every other session sends its question one level up; the phase frames it for the owner.",
  phase: "A phase session asks the owner questions that concern only its phase and tells the Console; the Console asks every other question. Milestones and tasks send their questions one level up.",
};

/** The rulebook every session reads: levels, names, questions, limits and the standing rules. */
export function rulebookPage(cfg, rules) {
  const [p, m, t] = ["A", "A.M1", "A.M1.T1"].map((id) => example(id, cfg));
  const checks = Object.entries(cfg.checks ?? {}).map(([level, list]) => `- ${level}: ${list.length ? list.map((c) => `\`${c}\``).join(", ") : "the project's own checks"}`);
  return [
    "# Syno Console: how this project's sessions work",
    "",
    GENERATED,
    "",
    "Syno Console runs this project as a tree of Claude Code sessions. If a session's first message and this page disagree, this page wins. Only the Console changes it.",
    "",
    "## The four levels",
    "",
    "| Level | Session title (example) | Branch (example) | Creates |",
    "| --- | --- | --- | --- |",
    `| Console | ${namesFor("console", "", cfg).title} | \`${cfg.syno?.branch ?? "(set at start)"}\` | Phase sessions |`,
    `| Phase | ${p.title} | \`${p.branch}\` | Milestone sessions |`,
    `| Milestone | ${m.title} | \`${m.branch}\` | Task sessions |`,
    `| Task | ${t.title} | \`${t.branch}\` | Nothing |`,
    "",
    "Each level creates only its next level, from its own session, so the Claude app shows the tree.",
    "",
    "## Questions",
    "",
    ASK[cfg.askAt] ?? ASK.console,
    "",
    "## Limits and pace",
    "",
    `- At most ${cfg.limits.maxTasks} tasks per milestone at once, only with separate lanes. At most ${cfg.limits.maxMilestones} milestones per phase at once.`,
    `- ${cfg.rolling ? "Rolling: each finished task goes up the chain as soon as it passes." : "A milestone hands off when all its tasks are merged."}`,
    `- Shared files: ${cfg.sharedFiles.length ? cfg.sharedFiles.map((f) => `\`${f}\``).join(", ") : "none listed"}. Merge recipe: ${cfg.mergeRecipe ? `\`${cfg.mergeRecipe}\`` : "none set"}.`,
    "",
    "## Checks after each merge",
    "",
    ...checks,
    "",
    "## Standing rules",
    "",
    ...rules.map((r) => `- **${r.id}** ${r.text}`),
    "",
    `The decision register is \`${cfg.register}\`. The records are in \`.syno/console/\`.`,
    "",
  ].join("\n");
}
